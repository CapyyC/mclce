#!/usr/bin/env bash
# Executes the Roblox glue (src/server, src/client) inside a mock DataModel in
# the Luau CLI. The mock checks API usage and remote/DataStore serialisation
# rules; it is NOT the real engine (no physics, rendering or networking).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
LUAU="${LUAU:-$ROOT/tools/bin/luau}"
OUT="$ROOT/tests/roblox/_bundle.luau"
python3 - "$ROOT" "$OUT" <<'PY'
import os, sys
root, out = sys.argv[1], sys.argv[2]
parts = ["-- GENERATED by scripts/test-roblox-mock.sh; do not edit or commit\nreturn {\n"]
for base in ("src",):
    for dp, dn, fn in os.walk(os.path.join(root, base)):
        dn.sort()
        for f in sorted(fn):
            if f.endswith(".luau") or f.endswith(".meta.json"):
                p = os.path.join(dp, f)
                rel = os.path.relpath(p, root).replace(os.sep, "/")
                src = open(p, encoding="utf-8").read()
                eq = "=" * 8
                while ("]" + eq + "]") in src:
                    eq += "="
                parts.append(f'\t["{rel}"] = [{eq}[{src}]{eq}],\n')
parts.append("}\n")
open(out, "w", encoding="utf-8").write("".join(parts))
PY
cd "$ROOT/tests/roblox"
if [ "$#" -gt 0 ]; then
  "$LUAU" run.luau -a "$@"
else
  "$LUAU" run.luau -a parts
  "$LUAU" run.luau -a mesh
fi
